embedder = None
classifier_mode = "TF-IDF fallback"

try:
    from sentence_transformers import SentenceTransformer
    embedder = SentenceTransformer("all-MiniLM-L6-v2")
    classifier_mode = "Sentence Transformers embeddings"
except Exception as e:
    print("Embedding model unavailable; using TF-IDF fallback.")
    print("Reason:", str(e)[:250])

def best_match(text, descriptions):
    labels = list(descriptions.keys())
    docs = [descriptions[k] for k in labels]
    if embedder is not None:
        vectors = embedder.encode([str(text)] + docs, normalize_embeddings=True)
        scores = cosine_similarity([vectors[0]], vectors[1:])[0]
    else:
        vectorizer = TfidfVectorizer(ngram_range=(1,2), stop_words="english")
        matrix = vectorizer.fit_transform([str(text)] + docs)
        scores = cosine_similarity(matrix[0:1], matrix[1:])[0]
    idx = int(np.argmax(scores))
    return labels[idx], float(scores[idx])

print("Classifier mode:", classifier_mode)

"""## Step 5 — Extract details from inquiry text"""

def extract_budget(text, provided_budget=""):
    if str(provided_budget).strip():
        try:
            return int(float(str(provided_budget).replace(",", "").strip()))
        except:
            pass

    t = str(text).lower().replace(",", "")
    # Examples: Rs 500000, INR 2 lakh, 5 lakhs, 3.5 crore
    patterns = [
        (r'(?:rs\.?|inr|₹)\s*(\d+(?:\.\d+)?)\s*(crore|cr|lakh| lakhs|lac|lacs|k)?', 1),
        (r'\b(\d+(?:\.\d+)?)\s*(crore|cr|lakh|lakhs|lac|lacs)\b', 1)
    ]
    for pattern, _ in patterns:
        m = re.search(pattern, t)
        if m:
            amount = float(m.group(1))
            unit = (m.group(2) or "").strip()
            multiplier = 1
            if unit in ["lakh", "lakhs", "lac", "lacs"]:
                multiplier = 100000
            elif unit in ["crore", "cr"]:
                multiplier = 10000000
            elif unit == "k":
                multiplier = 1000
            return int(amount * multiplier)
    return None

def extract_timeline(text, provided_timeline=""):
    if str(provided_timeline).strip() and str(provided_timeline).lower() not in ["not specified", "nan"]:
        return str(provided_timeline)
    t = str(text).lower()
    patterns = [
        r'\bwithin\s+\d+\s+(?:days?|weeks?|months?)\b',
        r'\b\d+\s+(?:days?|weeks?|months?)\b',
        r'\bnext\s+(?:week|month)\b',
        r'\b(?:urgent|as soon as possible|immediately|later this year)\b'
    ]
    for p in patterns:
        m = re.search(p, t)
        if m:
            return m.group(0)
    return "Not provided"

def extract_company_context(text, provided_industry=""):
    return str(provided_industry).strip() if str(provided_industry).strip() else "Not provided"

"""## Step 6 — Priority scoring and routing logic"""

def calculate_priority(text, budget, timeline, source_channel):
    t = str(text).lower()
    score = 0
    reasons = []

    # Budget signal: presence only; higher budget is not automatically better.
    if budget is not None:
        score += 20
        reasons.append("Budget information provided (+20)")

    # Timeline / urgency signal
    if any(word in t for word in ["urgent", "as soon as possible", "immediately", "this week"]):
        score += 25
        reasons.append("Urgent timing mentioned (+25)")
    elif timeline != "Not provided" and timeline != "Not specified":
        score += 15
        reasons.append("Timeline provided (+15)")

    # Intent signal
    if any(word in t for word in ["schedule", "demo", "proposal", "start", "begin", "looking to build", "need help", "need a"]):
        score += 20
        reasons.append("Action-oriented intent detected (+20)")

    # Requirement completeness
    detail_terms = ["app", "platform", "automation", "integration", "dashboard", "cloud", "crm", "website", "agent", "pipeline"]
    matched = sum(term in t for term in detail_terms)
    if matched >= 3:
        score += 25
        reasons.append("Detailed requirements detected (+25)")
    elif matched >= 1:
        score += 15
        reasons.append("Some requirements detected (+15)")
    else:
        score += 5
        reasons.append("Limited requirement detail (+5)")

    # Channel context: demo requests indicate explicit product interest
    if source_channel == "Product Demo":
        score += 10
        reasons.append("Explicit product demo interest (+10)")

    score = min(score, 100)
    if score >= 70:
        priority = "High"
    elif score >= 40:
        priority = "Medium"
    else:
        priority = "Low"
    return score, priority, reasons

def recommend_followup(category, priority, timeline):
    team, action = ROUTING.get(category, ROUTING["General / Needs Discovery"])
    if priority == "High":
        opening = "Thank you for sharing your requirements. Our team will prioritize reviewing your inquiry."
    elif priority == "Medium":
        opening = "Thank you for contacting Cynbit. We would be happy to understand your requirements in more detail."
    else:
        opening = "Thank you for your interest in Cynbit. We would be glad to learn more about what you are looking to achieve."
    return team, action, f"{opening} A member of our team can follow up to discuss the next steps. (Suggested draft — please review before sending.)"

"""## Step 7 — Create the end-to-end inquiry analysis function"""

def analyze_inquiry(inquiry_text, source_channel="Blueprint", industry="", budget="", timeline="", product=""):
    text = str(inquiry_text).strip()
    if not text:
        raise ValueError("Please enter an inquiry description.")

    # Classify service/product from the text, while honoring an explicit product field.
    category, confidence = best_match(text, SERVICE_DESCRIPTIONS)
    if str(product).strip() in ["Cynbit Studio", "TenantEase", "Revio"]:
        category = str(product).strip()

    extracted_budget = extract_budget(text, budget)
    extracted_timeline = extract_timeline(text, timeline)
    industry_value = extract_company_context(text, industry)

    score, priority, reasons = calculate_priority(
        text, extracted_budget, extracted_timeline, source_channel
    )
    team, next_action, followup = recommend_followup(category, priority, extracted_timeline)

    return {
        "Source channel": source_channel,
        "Predicted category": category,
        "Model similarity score": round(confidence, 3),
        "Industry": industry_value,
        "Budget (INR)": extracted_budget if extracted_budget is not None else "Not provided",
        "Timeline": extracted_timeline,
        "Priority score": score,
        "Priority": priority,
        "Scoring explanation": "; ".join(reasons),
        "Recommended team": team,
        "Suggested next action": next_action,
        "Follow-up draft": followup
    }

